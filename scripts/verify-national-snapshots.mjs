const agoraRows = states.filter((item) => item.agora2025);
assert.equal(agoraRows.length, 35);
assert.equal(states.find((item) => item.name === 'Rivers').agora2025, null);
const revenueTotal = agoraRows.reduce((sum, item) => sum + item.agora2025.actualRevenueBn, 0);
const expenditureTotal = agoraRows.reduce((sum, item) => sum + item.agora2025.actualExpenditureBn, 0);
const impliedBudget = agoraRows.reduce((sum, item) => sum + item.agora2025.actualExpenditureBn / (item.agora2025.budgetExecutionPct / 100), 0);
const weightedExecution = expenditureTotal / impliedBudget * 100;
const weightedIgrShare = agoraRows.reduce((sum, item) => sum + item.agora2025.actualRevenueBn * item.agora2025.igrSharePct / 100, 0) / revenueTotal * 100;
assert.ok(Math.abs(revenueTotal - 16638.8) < 0.1, 'transcribed revenue values must reconcile to Agora aggregate');
assert.ok(Math.abs(expenditureTotal - 19210.23) < 0.1, 'transcribed expenditure values must reconcile to Agora aggregate');
assert.ok(Math.abs(weightedExecution - 68.2) < 0.1, 'weighted state execution must reconcile to Agora aggregate');
assert.ok(Math.abs(weightedIgrShare - 25) < 0.5, 'weighted IGR share must reconcile to Agora rounded aggregate');
